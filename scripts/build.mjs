#!/usr/bin/env node
// Embed packs/*.json into the client module.
//
//   node scripts/build.mjs           write client.js
//   node scripts/build.mjs --check   fail if client.js is stale (CI / prepublish)
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { loadPacks } from './packs-lib.mjs'

const root = resolve(import.meta.dirname, '..')
const PLACEHOLDER = '/*__PACKS__*/[]'

const source = readFileSync(join(root, 'src', 'client.js'), 'utf8')
if (!source.includes(PLACEHOLDER)) throw new Error(`src/client.js lost its ${PLACEHOLDER} placeholder`)
const packs = loadPacks(join(root, 'packs'))
const banner = '// GENERATED by scripts/build.mjs from src/client.js and packs/*.json. Do not edit.\n'
const output = banner + source.replace(PLACEHOLDER, JSON.stringify(packs, null, 2).replace(/\n/g, '\n    '))

const target = join(root, 'client.js')
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch { /* missing counts as stale */ }
  if (current !== output) {
    console.error('client.js is stale: run `npm run build`')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  writeFileSync(target, output)
  console.log(`client.js written (${packs.length} packs, ${packs.reduce((n, p) => n + p.plugins.length, 0)} plugins)`)
}
execFileSync(process.execPath, ['--check', target], { stdio: 'inherit' })
